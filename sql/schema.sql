-- BlocoNaRua database schema (PostgreSQL / Npgsql)
-- Source: extracted from Supabase project "BlocoNaRua-Dev" (public schema), 2026-11-18.
-- Strategy: manually reviewed SQL script applied at deploy/bootstrap time (EF Core docs
-- recommend SQL scripts or migration bundles for production; NOT Database.Migrate() at startup).
-- No data migration — schema only.
--
-- Apply once via psql or the Dokploy postgres SQL console:
--   psql "Host=<host>;Port=5432;Database=postgres;Username=<user>;Password=<pass>" -f sql/schema.sql

CREATE TYPE roles AS ENUM ('Member', 'Manager', 'Owner');

CREATE TABLE members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL DEFAULT '',
    email varchar NOT NULL DEFAULT '',
    phone text NOT NULL DEFAULT '',
    profile_image text DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at timestamptz,
    uuid uuid NOT NULL DEFAULT gen_random_uuid(),
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT members_uuid_key UNIQUE (uuid)
);

CREATE TABLE carnival_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL DEFAULT '',
    invite_code text DEFAULT '',
    managers_invite_code text DEFAULT '',
    carnival_block_image text DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at timestamptz,
    owner_id bigint REFERENCES members(id),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE meetings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carnival_block_id bigint NOT NULL REFERENCES carnival_blocks(id) ON UPDATE CASCADE ON DELETE CASCADE,
    name text NOT NULL DEFAULT '',
    description text DEFAULT '',
    location text DEFAULT '',
    meeting_code text DEFAULT '',
    meeting_date_time timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE carnival_block_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carnival_block_id bigint NOT NULL REFERENCES carnival_blocks(id) ON UPDATE CASCADE ON DELETE CASCADE,
    member_id bigint NOT NULL REFERENCES members(id) ON UPDATE CASCADE ON DELETE SET DEFAULT,
    created_at timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at timestamptz,
    role roles NOT NULL,
    member_name text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT carnival_block_members_carnival_block_member_unique UNIQUE (carnival_block_id, member_id)
);

CREATE TABLE meeting_presences (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES members(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    meeting_id bigint NOT NULL REFERENCES meetings(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    carnival_block_id bigint NOT NULL REFERENCES carnival_blocks(id) ON UPDATE CASCADE ON DELETE CASCADE,
    is_present boolean NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT ix_meeting_presences_meeting_id_member_id UNIQUE (meeting_id, member_id)
);

CREATE TABLE api_errors (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    level text NOT NULL,
    source text,
    message text NOT NULL,
    stack_trace text,
    request_path text,
    request_method text,
    status_code integer,
    user_id text,
    additional_data jsonb,
    CONSTRAINT api_errors_level_check CHECK (level = ANY (ARRAY['Warning'::text, 'Error'::text, 'Critical'::text]))
);

-- Indexes (mirrors those created by migrations in Supabase, including the FK indexes)
CREATE INDEX ix_carnival_blocks_owner_id ON carnival_blocks (owner_id);
CREATE INDEX ix_carnival_block_members_member_id ON carnival_block_members (member_id);
CREATE INDEX ix_meetings_carnival_block_id ON meetings (carnival_block_id);
CREATE INDEX ix_meeting_presences_carnival_block_id ON meeting_presences (carnival_block_id);
CREATE INDEX ix_meeting_presences_member_id ON meeting_presences (member_id);
